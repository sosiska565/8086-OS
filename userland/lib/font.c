uint8_t font_widths[1104] = {0};

void font_calc_widths(void) {
    for (int i = 0; i < 1104; i++) {
        if (i == ' ') { font_widths[i] = 4; continue; }
        
        int max_x = -1;
        for (int y = 0; y < 8; y++) {
            for (int x = 0; x < 8; x++) {
                if ((font8x8_basic[i][y] >> x) & 1) {
                    if (x > max_x) max_x = x;
                }
            }
        }
        if (max_x == -1) font_widths[i] = 8;
        else font_widths[i] = max_x + 2; 
    }
}

int font_get_width(unsigned int c) {
    if (c < 1104) return font_widths[c];
    return 8;
}


uint32_t blend_colors(uint32_t fg, uint32_t bg, float alpha) {
    if (alpha <= 0.05f) return bg;
    if (alpha >= 0.95f) return fg;
    int r = ((fg >> 16) & 0xFF) * alpha + ((bg >> 16) & 0xFF) * (1.0f - alpha);
    int g = ((fg >> 8) & 0xFF) * alpha + ((bg >> 8) & 0xFF) * (1.0f - alpha);
    int b = (fg & 0xFF) * alpha + (bg & 0xFF) * (1.0f - alpha);
    return (r << 16) | (g << 8) | b;
}
